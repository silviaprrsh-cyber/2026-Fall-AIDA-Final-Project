def analyze(manifest_path):
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    if not manifest.get('requests_complete') or any(job['status'] not in {'downloaded', 'empty'} for job in manifest['jobs']):
        raise ValueError('Complete all planned requests before full-run analysis')
    if set(job['station_id'] for job in manifest['jobs']) != set(STATIONS):
        raise ValueError('Expected the five model stations')
    output = BASE / 'processed/model_unit_history' / manifest['run']
    output.mkdir(parents=True, exist_ok=True)
    building = output / 'unit_observations.build.sqlite3'
    if building.exists():
        building.unlink()
    db = sqlite3.connect(building)
    db.execute('CREATE TABLE parameter_observations (' + ','.join(
        name + (' REAL' if name == 'value' else ' TEXT') for name in FIELDS) +
        ', PRIMARY KEY(station_id,observed_at,parameter))')
    db.execute('CREATE TEMP TABLE incoming AS SELECT * FROM parameter_observations WHERE 0')
    report = {'run': manifest['run'], 'created_at': datetime.now(timezone.utc).isoformat(),
              'requested_start': manifest['start'], 'requested_end': manifest['end'],
              'daily_data_used': False, 'planned_requests': len(manifest['jobs']),
              'empty_requests': sum(job['status'] == 'empty' for job in manifest['jobs']),
              'raw_parameter_rows': 0, 'duplicate_parameter_rows': 0, 'conflicting_revisions': 0,
              'source_sha256': {}, 'stations': {}}
    jobs = []
    for job in manifest['jobs']:
        path = (WORKSPACE / job['path']).resolve()
        if not path.is_relative_to(WORKSPACE):
            raise ValueError('Input must remain within movetest')
        meta = json.loads(path.with_suffix('.csv.meta.json').read_text(encoding='utf-8'))
        if meta['status'] != 200:
            raise ValueError('Unexpected HTTP status')
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != job['sha256'] or digest != meta['sha256']:
            raise ValueError('Original response checksum mismatch')
        report['source_sha256'][job['path']] = digest
        jobs.append((meta['received_at_utc'], job, path))
    for received, job, path in sorted(jobs, key=lambda item: (item[0], str(item[2]))):
        incoming = []
        with path.open(encoding='utf-8-sig', newline='') as stream:
            reader = csv.reader(stream)
            next(reader)
            for row in reader:
                if not row:
                    continue
                instant = datetime.fromisoformat(row[1].replace('Z', '+00:00'))
                if instant.tzinfo is None or row[0] != job['station_id'] or row[2] not in job['parameters']:
                    raise ValueError('Invalid station, parameter or observation timezone')
                observed = instant.astimezone(timezone.utc).isoformat()
                incoming.append((row[0], observed, row[2], value_number(row[3]), row[3], *row[4:9],
                                 job['path'], received, row[1]))
        if len(incoming) != job['row_count']:
            raise ValueError('Manifest row count mismatch')
        report['raw_parameter_rows'] += len(incoming)
        db.execute('DELETE FROM incoming')
        db.executemany('INSERT INTO incoming VALUES (' + ','.join('?' for _ in FIELDS) + ')', incoming)
        duplicates_within = db.execute('SELECT count(*) FROM (SELECT station_id,observed_at,parameter,count(*) n FROM incoming GROUP BY 1,2,3 HAVING n>1)').fetchone()[0]
        if duplicates_within:
            raise ValueError('Duplicate parameter keys inside one response require review')
        duplicate_join = ' FROM incoming i JOIN parameter_observations p USING(station_id,observed_at,parameter)'
        report['duplicate_parameter_rows'] += db.execute('SELECT count(*)' + duplicate_join).fetchone()[0]
        changed = ' OR '.join(f'i.{field} IS NOT p.{field}' for field in FIELDS[3:10])
        report['conflicting_revisions'] += db.execute('SELECT count(*)' + duplicate_join + ' WHERE '+changed).fetchone()[0]
        db.execute('INSERT OR REPLACE INTO parameter_observations SELECT * FROM incoming')
        db.commit()
        print('Normalized', job['station_id'], job['chunk_id'], len(incoming), flush=True)
    report['unique_parameter_rows'] = db.execute('SELECT count(*) FROM parameter_observations').fetchone()[0]
    assert report['raw_parameter_rows'] - report['duplicate_parameter_rows'] == report['unique_parameter_rows']
    pivot = []
    for parameter, prefix in [('46', 'level'), ('47', 'discharge')]:
        for field in ['value', 'qualifier', 'symbol', 'approval', 'grade', 'qualifiers', 'source_path', 'received_at']:
            suffix = 'm' if parameter == '46' else 'm3_s'
            name = prefix + '_' + (suffix if field == 'value' else field)
            pivot.append(f"max(CASE WHEN parameter='{parameter}' THEN {field} END) AS {name}")
    db.execute('CREATE TABLE station_observations AS SELECT station_id,observed_at,' + ','.join(pivot) +
               ' FROM parameter_observations GROUP BY station_id,observed_at')
    db.execute('CREATE UNIQUE INDEX station_time ON station_observations(station_id,observed_at)')
    gaps = []
    for sid in STATIONS:
        times = [row[0] for row in db.execute('SELECT observed_at FROM station_observations WHERE station_id=? ORDER BY observed_at', (sid,))]
        instants = [datetime.fromisoformat(t) for t in times]
        intervals = [(b-a).total_seconds() for a, b in zip(instants, instants[1:])]
        histogram = Counter(intervals)
        cadence = histogram.most_common(1)[0][0] if histogram else None
        for previous, following, seconds in zip(times, times[1:], intervals):
            if cadence and seconds > cadence:
                gaps.append({'station_id': sid, 'previous_observed_at': previous, 'next_observed_at': following,
                             'gap_seconds': seconds, 'inferred_typical_interval_seconds': cadence,
                             'inferred_missing_slots': max(0, math.ceil(seconds/cadence)-1)})
        stats = {'observation_timestamps': len(times), 'first_observed_at': times[0] if times else None,
                 'last_observed_at': times[-1] if times else None, 'modal_interval_seconds': cadence,
                 'interval_histogram': dict(histogram), 'gaps_longer_than_mode': sum(s>cadence for s in intervals) if cadence else 0,
                 'longest_gap_seconds': max(intervals) if intervals else None}
        for name, expression in [('level_numeric', 'level_m>=0'), ('discharge_numeric', 'discharge_m3_s>=0'),
                                 ('paired_numeric', 'level_m>=0 AND discharge_m3_s>=0')]:
            stats[name] = db.execute(f'SELECT count(*) FROM station_observations WHERE station_id=? AND {expression}',(sid,)).fetchone()[0]
        for field in ['approval','grade','qualifier','symbol','qualifiers']:
            stats[field + '_counts'] = {str(key): count for key, count in db.execute(
                f'SELECT {field},count(*) FROM parameter_observations WHERE station_id=? GROUP BY {field}',(sid,))}
        stats['parameter_ranges'] = {}
        for parameter in (['46'] if sid == '05CC003' else ['46','47']):
            count, missing, minimum, maximum = db.execute(
                'SELECT count(*),sum(value IS NULL),min(value),max(value) FROM parameter_observations WHERE station_id=? AND parameter=?',
                (sid,parameter)).fetchone()
            stats['parameter_ranges'][parameter] = {'records': count, 'nonnumeric_records': missing or 0,
                                                    'minimum': minimum, 'maximum': maximum,
                                                    'unit': 'm' if parameter=='46' else 'm3/s'}
        report['stations'][sid] = stats
        export_query(db, output / (sid + '_observations.csv'),
                     f"SELECT * FROM station_observations WHERE station_id='{sid}' ORDER BY observed_at")
    selections = ['s0.observed_at']
    joins, conditions, screened_conditions = [], [], []
    for i, sid in enumerate(STATIONS):
        alias = 's' + str(i)
        joins.append(f"station_observations {alias}")
        conditions.extend([f"{alias}.station_id='{sid}'", f'{alias}.observed_at=s0.observed_at', f'{alias}.level_m>=0'])
        columns = ['level_m'] if sid == '05CC003' else ['level_m','discharge_m3_s']
        for column in columns:
            selections.append(f'{alias}.{column} AS "{sid}_{column}"')
            conditions.append(f'{alias}.{column}>=0')
            screened_conditions.append(f'"{sid}_{column}">0')
        for prefix in (['level'] if sid == '05CC003' else ['level','discharge']):
            for suffix in ['symbol','qualifiers','qualifier','grade','approval']:
                column = prefix+'_'+suffix
                selections.append(f'{alias}.{column} AS "{sid}_{column}"')
                if suffix in ['symbol','qualifiers']:
                    screened_conditions.append(f'coalesce("{sid}_{column}",\'\')=\'\'')
    db.execute('CREATE TABLE common_numeric AS SELECT '+','.join(selections)+' FROM '+','.join(joins)+' WHERE '+' AND '.join(conditions))
    db.execute('CREATE UNIQUE INDEX common_time ON common_numeric(observed_at)')
    db.execute('CREATE TABLE screened AS SELECT * FROM common_numeric WHERE '+' AND '.join(screened_conditions))
    report['common_numeric_timestamps'] = db.execute('SELECT count(*) FROM common_numeric').fetchone()[0]
    report['screened_timestamps'] = db.execute('SELECT count(*) FROM screened').fetchone()[0]
    export_query(db, output / 'common_numeric_unit_values.csv', 'SELECT * FROM common_numeric ORDER BY observed_at')
    export_query(db, output / 'screened_unit_values.csv', 'SELECT * FROM screened ORDER BY observed_at')
    selected_times = [row[0] for row in db.execute('SELECT observed_at FROM screened ORDER BY observed_at')]
    total = len(selected_times)
    first, second = int(total*0.6), int(total*0.6)+int(total*0.2)
    assignment = [(t, 'training' if i<first else 'validation' if i<second else 'test') for i,t in enumerate(selected_times)]
    db.execute('CREATE TABLE candidate_splits(observed_at TEXT PRIMARY KEY, partition TEXT)')
    db.executemany('INSERT INTO candidate_splits VALUES (?,?)', assignment)
    export_query(db, output / 'candidate_split_assignments.csv', 'SELECT * FROM candidate_splits ORDER BY observed_at')
    report['candidate_partition_counts'] = dict(Counter(partition for t,partition in assignment))
    report['candidate_partition_ranges'] = {name: {'first': min(t for t,n in assignment if n==name),
                                                    'last': max(t for t,n in assignment if n==name)}
                                           for name in report['candidate_partition_counts']}
    report['screening_policy'] = 'Positive finite level and river flow at identical observation timestamps. Symbol and Qualifiers fields blank. Numeric quality grades and provisional approvals retained.'
    report['split_status'] = 'candidate_origin_partition_before_propagation_alignment_and_target_purging'
    report['receipt_replay'] = 'Historical download receipt times do not establish original publication-time availability.'
    report['deduplication'] = 'Key station_id, UTC observed_at and parameter. Latest downloaded revision retained. Originals preserved.'
    with (output/'observed_gaps.csv').open('w',encoding='utf-8-sig',newline='') as stream:
        fields = ['station_id','previous_observed_at','next_observed_at','gap_seconds','inferred_typical_interval_seconds','inferred_missing_slots']
        writer=csv.DictWriter(stream,fieldnames=fields);writer.writeheader();writer.writerows(gaps)
    note(output/'observed_gaps.csv', 'Gaps inferred from each station modal observed interval. These are descriptive gaps, with no equipment-failure inference.')
    db.commit()
    if db.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
        raise ValueError('SQLite integrity failure')
    db.close()
    building.replace(output/'unit_observations.sqlite3')
    note(output/'unit_observations.sqlite3', 'Deduplicated parameter records, station timestamp pairs, common cohorts and candidate partitions. Raw values and quality fields remain queryable.')
    path = output/'analysis_report.json'
    path.write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    note(path, 'Download provenance, counts, observed cadences, gaps, quality distributions and candidate partition ranges.')
    write_readmes(output, manifest, report, manifest_path)
    print(json.dumps({key:report[key] for key in ['raw_parameter_rows','unique_parameter_rows','duplicate_parameter_rows',
                                                 'common_numeric_timestamps','screened_timestamps','candidate_partition_counts']},indent=2))
    print(output)
    return output


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest',type=Path,required=True)
    args=parser.parse_args()
    analyze(args.manifest.resolve())


if __name__=='__main__':
    main()
