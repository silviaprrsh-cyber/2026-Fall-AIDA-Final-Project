"""Offline ML entry point; never starts acquisition or a background service."""
import argparse
import csv
import json
from pathlib import Path
import sqlite3

from API.observations import parse_time
from project_paths import WORKSPACE
from rdr_eda.project_etl import companion
from rdr_eda.postgres import read_training_views
from .core import Chain, Dataset, fit, metrics


DATA = WORKSPACE / 'courses/AIDA-2156/data'
DEFAULT_DB = DATA / 'processed/project_etl/project.sqlite3'
DEFAULT_POLICY = WORKSPACE / 'shared-resources/config/segment_ml.json'
DEFAULT_OUTPUT = DATA / 'processed/segment_ml_05CC002'
DEFAULT_PG_CONFIG = WORKSPACE / 'shared-resources/config/postgres_dataset.json'


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + '\n'
    staging = path.with_name(path.name + '.tmp')
    try:
        staging.write_text(serialized, encoding='utf-8')
        staging.replace(path)
    finally:
        staging.unlink(missing_ok=True)
    companion(path,
              'Generated by run.py ml from the local scoped ETL and explicit model policy. '
              'Contains experimental model parameters, predictions or validation evidence; not source observations or flood warnings.',
              '由 run.py ml 根据本地范围化 ETL 与明确的模型配置生成，保存实验参数、预测或验证证据；不是原始观测，也不是洪水预警。')


def load_model(path, dataset):
    artifact = json.loads(path.read_text(encoding='utf-8-sig'))
    if artifact.get('schema_version') != 2 or artifact.get('model_type') != 'regularized_recursive_endpoint_calibration':
        raise ValueError('Unsupported model artifact')
    if artifact['policy'] != dataset.policy or artifact['segments'] != dataset.segments:
        raise ValueError('Policy or river graph changed: use the matching model or retrain')
    if artifact['geometry_sha256'] != dataset.geometry_sha256:
        raise ValueError('Section geometry changed: retrain before using this snapshot')
    return artifact, Chain(dataset, artifact['parameters'], artifact['lake_center'], artifact['lake_scale'])


def write_states(path, predictions, artifact):
    fields = ['trajectory_id', 'forecast_origin_at', 'node_id', 'segment_id', 'state_kind',
              'discharge_m3_s', 'experimental_variable_depth_m', 'velocity_m_s', 'area_m2',
              'section_id', 'estimated_arrival_at', 'model_version', 'training_data_end_at', 'trajectory_status']
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        for result in predictions:
            for state in result['states']:
                writer.writerow({**state, 'trajectory_id': result['trajectory_id'],
                                 'forecast_origin_at': result['forecast_origin_at'],
                                 'model_version': artifact['model_version'],
                                 'training_data_end_at': artifact['training_data_end_at'],
                                 'trajectory_status': result['status']})
    companion(path,
              'Per-node experimental predictions from run.py ml. Read trajectory_status before using any row: '
              'failed trajectories may contain partial states. Source geometry adapters are distinguished from model predictions; '
              'this is not the ETL --segment-states interchange format. Full provenance and endpoint matches are in the adjacent JSON.',
              'run.py ml 的逐节点实验预测。使用前检查 trajectory_status：失败轨迹可能保留部分节点。源站几何适配结果与模型预测分开标记；'
              '这不是 ETL --segment-states 的交换格式。完整来源与终点匹配见相邻 JSON。')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['inspect', 'train', 'evaluate', 'predict'])
    parser.add_argument('--database', type=Path, default=DEFAULT_DB)
    parser.add_argument('--source', choices=['postgres','sqlite'], default='postgres')
    parser.add_argument('--pg-config', type=Path, default=DEFAULT_PG_CONFIG)
    parser.add_argument('--config', type=Path, default=DEFAULT_POLICY)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--model', type=Path)
    parser.add_argument('--origin', help='Timezone-aware forecast origin for predict')
    parser.add_argument('--iterations', type=int, help='Finite optimizer budget for train')
    args = parser.parse_args(argv)
    output = args.output.resolve()
    if not output.is_relative_to(DATA.resolve() / 'processed'):
        parser.error('Model artifacts must stay in this course data/processed directory')
    report_path = DATA / 'reports/segment_ml_readiness.json'
    try:
        policy = json.loads(args.config.read_text(encoding='utf-8-sig'))
        if not 0 < policy['training_fraction'] < 1:
            raise ValueError('training_fraction must be strictly between zero and one')
        if any(policy[k] <= 0 for k in ['max_transit_seconds', 'source_max_age_seconds',
                                      'lake_max_age_seconds', 'target_match_tolerance_seconds',
                                      'minimum_training_pairs', 'minimum_validation_pairs', 'minimum_test_pairs']):
            raise ValueError('Time limits and minimum sample counts must be positive')
        if args.source == 'postgres':
            tables, partitions, metadata = read_training_views(args.pg_config)
            dataset = Dataset(None, policy, tables=tables, partitions=partitions, source_metadata=metadata)
        else:
            dataset = Dataset(args.database, policy)
        readiness = dataset.readiness()
        write_json(report_path, readiness)
        if args.command == 'inspect':
            print(json.dumps(readiness, indent=2))
            return 0
        if args.command == 'train':
            artifact, report, results = fit(dataset, args.iterations)
            write_json(output / 'model.json', artifact)
            write_json(output / 'training_report.json', report)
            write_json(output / 'holdout_predictions.json', results)
            write_states(output / 'holdout_states.csv', results, artifact)
            write_json(DATA / 'reports/segment_ml_training.json', report)
            print(json.dumps({'model': str(output / 'model.json'), 'holdout': report['holdout'],
                              'holdout_sufficient': artifact['holdout_sufficient'],
                              'calibration_only': artifact['calibration_only'],
                              'common_origins': report['overlap_selection']['common_origins']}, indent=2))
            return 0
        artifact, model = load_model(args.model or output / 'model.json', dataset)
        if not readiness['ready_for_calibration']:
            raise ValueError('; '.join(readiness['blocking_issues']))
        if args.command == 'predict':
            if not args.origin:
                raise ValueError('predict requires --origin with an explicit timezone')
            if not (args.origin.endswith('Z') or '+' in args.origin[10:] or '-' in args.origin[10:]):
                raise ValueError('Forecast origin must have an explicit timezone')
            origin = parse_time(args.origin)
            if origin <= parse_time(artifact.get('selection_data_end_at', artifact['training_data_end_at'])):
                raise ValueError('Forecast origin must be after the model training data cutoff')
            result = model.predict(origin)
            write_json(output / 'prediction.json', {'model_version': artifact['model_version'],
                        'input_sha256': dataset.sha256, 'prediction': result})
            write_states(output / 'prediction_states.csv', [result], artifact)
            print(json.dumps({'status': result['status'], 'output': str(output / 'prediction.json')}))
            return 0 if result['status'] == 'predicted' else 2
        split = parse_time(artifact.get('test_split_at', artifact['split_at']))
        origins, _ = dataset.common_origins()
        results = [model.scored(t, lower=split) for t in origins if t >= split]
        report = {'model_version': artifact['model_version'], 'input_sha256': dataset.sha256,
                  'training_snapshot_sha256': artifact['input_sha256'], 'holdout': metrics(results),
                  'calibration_only': artifact.get('calibration_only', False)}
        write_json(output / 'evaluation_predictions.json', results)
        write_json(DATA / 'reports/segment_ml_evaluation.json', report)
        print(json.dumps(report, indent=2))
        return 0
    except (ValueError, KeyError, OSError, RuntimeError, sqlite3.DatabaseError) as exc:
        if hasattr(exc, 'report'):
            write_json(DATA / 'reports/segment_ml_split.json', exc.report)
        write_json(DATA / 'reports/segment_ml_last_error.json', {'command': args.command, 'error': str(exc)})
        print('ML not completed: ' + str(exc))
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
