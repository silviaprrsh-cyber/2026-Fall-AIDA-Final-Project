EVAL = '''//VERSION=3
function setup() {return {input:[{bands:["B04","B03","B02","B08","SCL","dataMask"]}],mosaicking:"TILE",output:{id:"image",bands:6,sampleType:"UINT16"}};}
function evaluatePixel(samples) {
 let s=samples.find(x=>x.dataMask===1);
 return s ? [Math.max(0,s.B04)*10000,Math.max(0,s.B03)*10000,Math.max(0,s.B02)*10000,Math.max(0,s.B08)*10000,s.SCL,s.dataMask] : [0,0,0,0,0,0];
}
function updateOutputMetadata(scenes,inputMetadata,outputMetadata) {outputMetadata.userData={tiles:scenes.tiles};}
'''


def save(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix+'.tmp')
    temporary.write_text(json.dumps(value,indent=2)+'\n',encoding='utf-8')
    temporary.replace(path)
    companion(path, 'Satellite history acquisition metadata, provenance or time matching. Generated by API.download_satellite_history.',
              'API.download_satellite_history 生成的卫星历史获取元数据、来源或时间匹配记录。')


def instant(value):
    return datetime.fromisoformat(value.replace('Z','+00:00'))


def request(session, method, url, **kwargs):
    for attempt in range(3):
        try:
            response=session.request(method,url,timeout=180,allow_redirects=False,**kwargs)
        except requests.RequestException:
            if attempt==2: raise RuntimeError('Network request failed after three attempts') from None
            time.sleep(2**attempt)
            continue
        if response.status_code==200: return response
        if response.status_code not in [429,500,502,503,504] or attempt==2:
            raise RuntimeError('Provider HTTP '+str(response.status_code))
        delay=response.headers.get('Retry-After','5')
        time.sleep(min(float(delay) if delay.isdigit() else 5,30))
    raise RuntimeError('Request failed')


def token(session, path):
    values={}
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        match=re.match(r'^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$',line)
        if match: values[match[1].upper()]=match[2].strip().strip('"').strip("'")
    client=next((values[k] for k in ['CDSE_CLIENT_ID','SH_CLIENT_ID','CLIENT_ID'] if values.get(k)),None)
    secret=next((values[k] for k in ['CDSE_CLIENT_SECRET','SH_CLIENT_SECRET','CLIENT_SECRET'] if values.get(k)),None)
    if not client or not secret: raise RuntimeError('Satellite credentials are missing')
    result=request(session,'POST',TOKEN,data={'grant_type':'client_credentials','client_id':client,'client_secret':secret}).json()
    return result['access_token'], time.monotonic()+max(30,int(result.get('expires_in',300))-30)


def nearest(times, target):
    i=bisect_left(times,target)
    options=times[max(0,i-1):i+1]
    value=min(options,key=lambda t:abs((t-target).total_seconds())) if options else None
    delta=(value-target).total_seconds() if value else None
    return {'observed_at':value.isoformat() if value else None,'offset_seconds':delta,
            'within_150_seconds':delta is not None and abs(delta)<=150}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run-id',default=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ'))
    parser.add_argument('--credential-file',type=Path,default=WORKSPACE/'.env')
    parser.add_argument('--catalog-only',action='store_true')
    parser.add_argument('--workers',type=int,default=4)
    args=parser.parse_args()
    if not re.fullmatch(r'[A-Za-z0-9_-]+',args.run_id): raise ValueError('Invalid run identifier')
    raw=BASE/'sources/copernicus_sentinel2/raw/history'/args.run_id
    report_dir=BASE/'reports/satellite_history'/args.run_id
    manifest_path=report_dir/'manifest.json'
    raw.mkdir(parents=True,exist_ok=True)
    geometry_path=WORKSPACE/'courses/AIDA-2362/project/nrcan_nhn/selected_rivers.geojson'
    river=unary_union([shape(f['geometry']) for f in json.loads(geometry_path.read_text())['features']])
    forward=Transformer.from_crs(4326,32612,always_xy=True).transform
    reverse=Transformer.from_crs(32612,4326,always_xy=True).transform
    corridor=transform(forward,river).buffer(500)
    geographic=transform(reverse,corridor)
    dbpath=WORKSPACE/'courses/AIDA-2156/data/processed/model_unit_history/20261103T070414Z/unit_observations.sqlite3'
    with sqlite3.connect(dbpath.resolve().as_uri()+'?mode=ro',uri=True) as db:
        origins=[instant(r[0]) for r in db.execute('SELECT observed_at FROM candidate_splits ORDER BY observed_at')]
        station_times={sid:[instant(r[0]) for r in db.execute('SELECT observed_at FROM station_observations WHERE station_id=? ORDER BY observed_at',(sid,))] for sid in ['05CB007','05CB001','05CC007','05CC003','05CC002']}
    start,end=origins[0],origins[-1]
    boundaries={'60_20_20':[origins[int(len(origins)*.6)],origins[int(len(origins)*.6)+int(len(origins)*.2)]],
                '80_20':[origins[int(len(origins)*.8)]]}
    session=requests.Session()
    if manifest_path.exists():
        manifest=json.loads(manifest_path.read_text())
        if manifest['river_sha256']!=hashlib.sha256(geometry_path.read_bytes()).hexdigest(): raise RuntimeError('River geometry changed; use a new run identifier')
    else:
        features=[]
        query={'collections':['sentinel-2-l2a'],'bbox':list(geographic.bounds),'datetime':start.isoformat()+'/'+end.isoformat(),
               'limit':100,'filter-lang':'cql2-json','filter':{'op':'<=','args':[{'property':'eo:cloud_cover'},20]}}
        url=STAC
        page=0
        while True:
            page+=1
            if page>100: raise RuntimeError('Catalogue exceeded 100 pages; completeness not established')
            save(raw/f'catalog_request_{page:03}.json',query)
            response=request(session,'POST',url,json=query)
            catalogue=response.json()
            save(raw/f'catalog_response_{page:03}.json',catalogue)
            features.extend(catalogue.get('features',[]))
            link=next((l for l in catalogue.get('links',[]) if l.get('rel')=='next'),None)
            print('Catalogue page',page,'scenes',len(features),flush=True)
            if not link: break
            if not link['href'].startswith('https://stac.dataspace.copernicus.eu/'): raise RuntimeError('Unexpected pagination host')
            url=link['href']
            query={**query,**link.get('body',{})} if link.get('merge',False) else link.get('body',query)
        unique={f['id']:f for f in features if f.get('geometry') and shape(f['geometry']).intersects(geographic)}
        groups={}
        for f in unique.values():
            t=instant(f['properties']['datetime'])
            key=t.strftime('%Y%m%dT%H%M')+'_'+str(f['properties'].get('sat:relative_orbit','unknown'))
            groups.setdefault(key,[]).append(f)
        chunks=[]
        for x in range(math.floor(corridor.bounds[0]/10000)*10000,math.ceil(corridor.bounds[2]/10000)*10000,10000):
            for y in range(math.floor(corridor.bounds[1]/10000)*10000,math.ceil(corridor.bounds[3]/10000)*10000,10000):
                cell=box(x,y,x+10000,y+10000)
                clipped=cell.intersection(corridor)
                if not clipped.is_empty: chunks.append((f'{x}_{y}',[x,y,x+10000,y+10000],clipped))
        jobs=[]
        for key,scenes in sorted(groups.items()):
            footprint=unary_union([transform(forward,shape(f['geometry'])) for f in scenes])
            t=instant(scenes[0]['properties']['datetime'])
            for cid,bounds,clip in chunks:
                if not footprint.intersects(clip): continue
                jobs.append({'id':key+'_'+cid,'scene_time':t.isoformat(),'scene_ids':[f['id'] for f in scenes],
                             'bounds':bounds,'geometry':mapping(clip),'status':'pending'})
        manifest={'run_id':args.run_id,'started_at':datetime.now(timezone.utc).isoformat(),'time_start':start.isoformat(),'time_end':end.isoformat(),
                  'scope':'Dickson outlet to Joffre Bridge and selected tributaries; 500 m corridor buffer',
                  'river_sha256':hashlib.sha256(geometry_path.read_bytes()).hexdigest(),'cloud_threshold_percent':20,'pixel_size_m':10,
                  'catalog_complete':True,'catalog_scenes':len(unique),'acquisition_groups':len(groups),'grid_cells':len(chunks),
                  'bands':['B04','B03','B02','B08','SCL','dataMask'],'reflectance_scale':10000,
                  'quality_note':'SCL is native 20 m resampled to 10 m; clouds, shadow, snow/ice and missing pixels are not dry land.',
                  'jobs':jobs}
        save(manifest_path,manifest)
    print('Catalogue complete:',manifest['catalog_scenes'],'scenes,',len(manifest['jobs']),'image requests',flush=True)
    if args.catalog_only: return 0
    access,expiry=token(session,args.credential_file)
    lock=threading.Lock()
    auth_lock=threading.Lock()
    stopped=threading.Event()
    def download(item):
        nonlocal access,expiry
        number,job=item
        if stopped.is_set(): return 2
        session=requests.Session()
        folder=raw/job['id']
        archive_path=folder/job.get('archive_name','process_response.tar')
        if job['status'] in ['downloaded','no_data']:
            if not archive_path.exists() or hashlib.sha256(archive_path.read_bytes()).hexdigest()!=job['sha256']: raise RuntimeError('Archived image hash mismatch')
            return 0
        folder.mkdir(parents=True,exist_ok=True)
        attempt=len(list(folder.glob('process_response*.tar')))+1
        archive_path=folder/f'process_response_attempt{attempt}.tar'
        t=instant(job['scene_time'])
        extent=shape(job['geometry']).bounds
        bounds=[math.floor(extent[0]/10)*10,math.floor(extent[1]/10)*10,math.ceil(extent[2]/10)*10,math.ceil(extent[3]/10)*10]
        width,height=int((bounds[2]-bounds[0])/10),int((bounds[3]-bounds[1])/10)
        scene_filter='\nfunction preProcessScenes(collections) { let allowed='+json.dumps(job['scene_ids'])+'; collections.scenes.tiles=collections.scenes.tiles.filter(s=>allowed.indexOf((s.sentinel2ProductId || s.productId || "").replace(/\\.SAFE$/, ""))>=0); return collections; }\n'
        payload={'input':{'bounds':{'bbox':bounds,'geometry':job['geometry'],'properties':{'crs':'http://www.opengis.net/def/crs/EPSG/0/32612'}},
                         'data':[{'type':'sentinel-2-l2a','dataFilter':{'timeRange':{'from':(t-timedelta(minutes=30)).isoformat(),'to':(t+timedelta(minutes=30)).isoformat()},'maxCloudCoverage':20,'mosaickingOrder':'mostRecent'},'processing':{'upsampling':'NEAREST','downsampling':'NEAREST'}}]},
                 'output':{'width':width,'height':height,'responses':[{'identifier':'image','format':{'type':'image/tiff'}},{'identifier':'userdata','format':{'type':'application/json'}}]},'evalscript':EVAL+scene_filter}
        save(folder/f'process_request_attempt{attempt}.json',payload)
        try:
            with auth_lock:
                if time.monotonic()>expiry: access,expiry=token(session,args.credential_file)
            response=request(session,'POST',PROCESS,json=payload,headers={'Authorization':'Bearer '+access,'Accept':'application/tar'})
            if archive_path.exists(): raise RuntimeError('Existing unverified archive requires inspection before retry')
            archive_path.write_bytes(response.content)
            companion(archive_path,'Original Process API response containing image.tif (six bands) and userdata.json. Reflectance bands are scaled by 10000. Source image times are in userdata.json.',
                      'Process API 原始响应，含六波段 image.tif 及 userdata.json；反射率乘以 10000 保存，实际影像时间见 userdata.json。')
            with tarfile.open(fileobj=io.BytesIO(response.content)) as tar:
                names=tar.getnames()
                if set(names)!={'image.tif','userdata.json'}: raise RuntimeError('Unexpected response archive members')
                metadata=json.load(tar.extractfile('userdata.json'))
                if any(tile.get('sentinel2ProductId',tile.get('productId','')).removesuffix('.SAFE') not in job['scene_ids'] for tile in metadata.get('tiles',[])):
                    raise RuntimeError('Returned source product outside selected acquisition group')
                with MemoryFile(tar.extractfile('image.tif').read()) as mem,mem.open() as raster:
                    if raster.count!=6 or raster.shape!=(height,width) or raster.crs.to_epsg()!=32612 or raster.res!=(10,10) or not np.allclose(raster.bounds,bounds): raise RuntimeError('Unexpected raster geometry')
                    scl,mask=raster.read([5,6])
                    aoi=geometry_mask([job['geometry']],out_shape=raster.shape,transform=raster.transform,invert=True)
                    valid=(mask==1)&aoi
                    clear=valid&np.isin(scl,[4,5,6])
                    quality={'valid_corridor_fraction':float(valid.sum()/max(1,aoi.sum())),
                             'clear_corridor_fraction':float(clear.sum()/max(1,aoi.sum())),
                             'cloud_shadow_fraction':float((valid&np.isin(scl,[3,8,9,10])).sum()/max(1,valid.sum())),
                             'snow_ice_fraction':float((valid&(scl==11)).sum()/max(1,valid.sum()))}
            times=sorted(set(tile['date'] for tile in metadata.get('tiles',[])))
            if not times:
                if quality['valid_corridor_fraction']!=0: raise RuntimeError('Valid image has no sensing metadata')
                with lock:
                    job.update(status='no_data',archive_name=archive_path.name,sha256=hashlib.sha256(response.content).hexdigest(),bytes=len(response.content),quality=quality,
                               reason='Catalogue footprint intersects corridor but Process API returned no valid source pixels',received_at=datetime.now(timezone.utc).isoformat())
                    job.pop('error',None)
                    save(manifest_path,manifest)
                print('No valid source pixels',number,'/',len(manifest['jobs']),job['id'],flush=True)
                return 0
            matches=[]
            for value in times:
                actual=instant(value)
                if abs((actual-t).total_seconds())>1800: raise RuntimeError('Source image outside requested acquisition window')
                splits={}
                for name,edges in boundaries.items():
                    splits[name]=('train' if actual<edges[0] else 'test') if len(edges)==1 else ('train' if actual<edges[0] else 'validation' if actual<edges[1] else 'test')
                matches.append({'sensing_at':actual.isoformat(),'common_origin':nearest(origins,actual),'stations':{sid:nearest(values,actual) for sid,values in station_times.items()},'partitions':splits})
            save(folder/'sensing_and_water_matches.json',{'source_metadata':metadata,'matches':matches,'quality':quality,'matching_note':'Nearest observation within 150 seconds is contemporaneous evidence, not a routed endpoint target. Missing values are not interpolated.'})
            job.pop('error',None)
            job.update(status='downloaded',archive_name=archive_path.name,sha256=hashlib.sha256(response.content).hexdigest(),bytes=len(response.content),quality=quality,
                       processing_units=response.headers.get('x-processingunits-spent'),received_at=datetime.now(timezone.utc).isoformat())
        except (RuntimeError,requests.RequestException) as exc:
            job.update(status='failed',error=str(exc) if isinstance(exc,RuntimeError) else 'Network error')
            stopped.set()
            with lock: save(manifest_path,manifest)
            print('Stopped:',job['id'],job['error'],flush=True)
            return 2
        with lock: save(manifest_path,manifest)
        print('Downloaded',number,'/',len(manifest['jobs']),job['id'],'clear',round(quality['clear_corridor_fraction'],3),flush=True)
        return 0
    with ThreadPoolExecutor(max_workers=max(1,min(args.workers,4))) as pool:
        statuses=list(pool.map(download,enumerate(manifest['jobs'],1)))
    if any(statuses): return 2
    manifest['finished_at']=datetime.now(timezone.utc).isoformat()
    save(manifest_path,manifest)
    return 0


if __name__=='__main__':
    raise SystemExit(main())
